"""Unit tests for scripts/doc_pairing.py."""

from __future__ import annotations

from pathlib import Path

import doc_pairing as dp

ZH = '''# 标题

[English](README.en.md) | 中文

## 概览

正文段落。

### 列表

- 第一项
- 第二项

```python
print('hi')
```
'''
EN = '''# Title

English | [中文](README.md)

## Overview

Body paragraph.

### Lists

- First item
- Second item

```python
print('hi')
```
'''


def parse(text: str, name: str = 'README.md') -> dp.Document:
    return dp.parse_document(Path(name), text=text)


def test_slugify_keeps_cjk_and_strips_punctuation() -> None:
    assert dp.slugify('示例 项目：概览') == '示例-项目概览'
    assert dp.slugify('Hello, World!') == 'hello-world'
    assert dp.slugify('使用 `MCP` 工具') == '使用-mcp-工具'
    assert dp.slugify('***') == 'section'


def test_parse_document_builds_nested_section_keys() -> None:
    document = parse(ZH)
    assert not document.parse_errors
    assert [section.key for section in document.sections] == ['/标题', '/标题/概览', '/标题/概览/列表']
    assert [section.level for section in document.sections] == [1, 2, 3]
    assert [block.kind for block in document.sections[2].blocks] == ['list', 'code']


def test_parse_document_deduplicates_duplicate_headings() -> None:
    document = parse('# A\n\n## 概览\n\nx\n\n## 概览\n\ny\n')
    assert [section.key for section in document.sections] == ['/a', '/a/概览', '/a/概览~2']


def test_parse_document_reports_heading_and_preamble_errors() -> None:
    assert '一级标题' in parse('## 二级\n').parse_errors[0]
    assert '一级标题' in parse('前言\n\n# 标题\n').parse_errors[0]


def test_parse_blocks_captures_code_info_and_body() -> None:
    code = next(block for block in parse(ZH).blocks if block.kind == 'code')
    assert code.info == 'python'
    assert code.body == "print('hi')"
    assert code.line == 14


def test_section_text_excludes_code_blocks() -> None:
    document = parse(ZH)
    before = dp.compute_hashes(document)
    edited = parse(ZH.replace("print('hi')", "print('bye')"))
    assert dp.compute_hashes(edited) == before


def test_aligned_hashes_keys_are_primary_document_keys() -> None:
    record, error = dp.aligned_hashes(parse(ZH), parse(EN, 'README.en.md'))
    assert error is None
    assert list(record) == ['/标题', '/标题/概览', '/标题/概览/列表']
    en_hash, zh_hash = record['/标题/概览']
    assert en_hash != zh_hash


def test_aligned_hashes_rejects_section_count_mismatch() -> None:
    record, error = dp.aligned_hashes(parse(ZH), parse('Text without heading.\n', 'README.en.md'))
    assert record is None
    assert error is not None and '小节数量不一致' in error


def test_record_roundtrip_and_headers_ignored() -> None:
    record, error = dp.aligned_hashes(parse(ZH), parse(EN, 'README.en.md'))
    assert error is None
    rendered = dp.render_record(record)
    parsed, errors = dp.parse_record(rendered)
    assert not errors
    assert parsed == record
    assert rendered.endswith('\n')
    assert rendered.startswith('# Generated by scripts/verify_docs.py')


def test_parse_record_reports_malformed_entries() -> None:
    _, errors = dp.parse_record('/a:\n  en: 0123456789abcdef\n  zh: 0123456789abcdef\n')
    assert not errors
    _, errors = dp.parse_record('not-a-key\n  en: 0123456789abcdef\n  zh: 0123456789abcdef\n')
    assert errors
    _, errors = dp.parse_record('/a:\n')
    assert any('截断' in message for message in errors)
    _, errors = dp.parse_record('/a:\n  en: xyz\n  zh: 0123456789abcdef\n')
    assert any('格式' in message for message in errors)
    _, errors = dp.parse_record(
        '/a:\n  en: 0123456789abcdef\n  zh: 0123456789abcdef\n'
        '/a:\n  en: 0123456789abcdef\n  zh: 0123456789abcdef\n'
    )
    assert any('重复' in message for message in errors)


def test_switcher_lines_use_primary_and_english_names() -> None:
    assert dp.switcher_line('zh', 'README.md') == '[English](README.en.md) | 中文'
    assert dp.switcher_line('en', 'README.md') == 'English | [中文](README.md)'


def test_extract_links_ignores_inline_code_and_images() -> None:
    raw = '普通 [链接](a.md)，`[代码](b.md)`，图片 ![图](c.png)。'
    assert dp.extract_links(raw) == ['a.md', 'c.png']


def test_semantic_target_normalizes_locale_suffix_only() -> None:
    assert dp.semantic_target('docs/x.en.md#a') == 'docs/x.md#a'
    assert dp.semantic_target('https://example.com/x.md') == 'https://example.com/x.md'


def test_structure_tokens_equal_for_translations() -> None:
    assert dp.structure_tokens(parse(ZH)) == dp.structure_tokens(parse(EN, 'README.en.md'))


def test_structure_tokens_detect_shape_differences() -> None:
    zh_tokens = dp.structure_tokens(parse(ZH))
    changed_list = dp.structure_tokens(parse(ZH.replace('- 第二项\n', '- 第二项\n- 第三项\n')))
    assert zh_tokens != changed_list
    changed_link = dp.structure_tokens(parse(ZH.replace('正文段落。', '正文 [链接](docs/x.md)。')))
    assert zh_tokens != changed_link


def test_pair_files_paths() -> None:
    zh, en, record = dp.pair_files(Path('docs/architecture.md'))
    assert (zh.as_posix(), en.as_posix(), record.as_posix()) == (
        'docs/architecture.md',
        'docs/architecture.en.md',
        'docs/architecture.i18n.yaml',
    )
