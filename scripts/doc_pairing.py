"""中文主文档 + 英文配对三件套的解析、哈希与结构对照工具。

本模块只依赖标准库。门禁命令见 ``scripts/verify_docs.py``，规则本身见
``docs/i18n/README.md`` 与 ``docs/AGENTS.md``。
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass, field
from pathlib import Path

HEADING_RE = re.compile(r'^(#{1,6})\s+(.*?)\s*#*\s*$')
FENCE_RE = re.compile(r'^(\s*)(`{3,}|~{3,})(.*)$')
LIST_RE = re.compile(r'^(\s*)([-*+]|\d+[.)])\s+')
TABLE_RE = re.compile(r'^\s*\|')
QUOTE_RE = re.compile(r'^\s*>')
THEMATIC_RE = re.compile(r'^\s{0,3}([-*_])(\s*\1){2,}\s*$')
SEPARATOR_RE = re.compile(r'^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$')
INLINE_CODE_RE = re.compile(r'`+[^`\n]*`+')
HTML_COMMENT_RE = re.compile(r'<!--.*?-->', re.DOTALL)
LINK_RE = re.compile(r'\[[^\]]*\]\(\s*([^)\s]+)(?:\s+"[^"]*")?\s*\)')
REF_LINK_RE = re.compile(r'^\s*\[[^\]]+\]:\s*(\S+)')
GENERATED_BEGIN = '<!-- i18n:begin -->'
GENERATED_END = '<!-- i18n:end -->'

RECORD_HEADER = (
    '# Generated by scripts/verify_docs.py pairing --write; do not edit by hand.',
    '# One entry per Markdown heading section; fenced code blocks are excluded from hashes.',
    '# Re-record: python scripts/verify_docs.py pairing --write <source>.',
    '# Keys are heading-slug paths from the primary (Chinese) document.',
)

NOTE_LINK_SUFFIXES = ('.md', '.en.md')


@dataclass
class Block:
    """A top-level Markdown node. Headings carry ``level``/``text``, code blocks ``info``/``body``."""

    kind: str
    raw: str
    line: int
    level: int = 0
    text: str = ''
    info: str = ''
    body: str = ''


@dataclass
class Section:
    """One heading and every block up to the next heading."""

    key: str
    level: int
    heading: str
    line: int
    blocks: list[Block] = field(default_factory=list)


@dataclass
class Document:
    path: Path
    text: str
    blocks: list[Block]
    sections: list[Section]
    preamble: list[Block]
    parse_errors: list[str] = field(default_factory=list)


def slugify(text: str) -> str:
    """Return a stable heading slug that keeps CJK characters."""
    value = text.strip()
    value = re.sub(r'`([^`]*)`', r'\1', value)
    value = re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', value)
    value = re.sub(r'[*_~]{1,3}', '', value)
    value = value.lower().replace(' ', '-')
    value = re.sub(r'[^\w\-]', '', value)
    value = re.sub(r'-{2,}', '-', value).strip('-')
    return value or 'section'


def normalize_raw(lines: list[str]) -> str:
    """Strip trailing whitespace per line and surrounding blank lines."""
    return '\n'.join(line.rstrip() for line in lines).strip('\n')


def parse_blocks(text: str) -> list[Block]:
    """Split Markdown into top-level blocks without third-party parsers."""
    lines = text.splitlines()
    blocks: list[Block] = []
    index = 0
    total = len(lines)
    paragraph: list[str] = []
    paragraph_start = 0

    def flush_paragraph() -> None:
        nonlocal paragraph
        if paragraph:
            blocks.append(Block('paragraph', normalize_raw(paragraph), paragraph_start))
            paragraph = []

    while index < total:
        line = lines[index]
        stripped = line.strip()

        fence = FENCE_RE.match(line)
        if fence:
            flush_paragraph()
            start = index
            marker = fence.group(2)
            close_re = re.compile(r'^\s*' + re.escape(marker[0]) + '{' + str(len(marker)) + r',}\s*$')
            body: list[str] = []
            index += 1
            while index < total and not close_re.match(lines[index]):
                body.append(lines[index])
                index += 1
            raw_lines = [line, *body]
            if index < total:
                raw_lines.append(lines[index])
            blocks.append(Block('code', normalize_raw(raw_lines), start + 1, info=fence.group(3).strip(), body=normalize_raw(body)))
            index += 1
            continue

        if not stripped:
            flush_paragraph()
            index += 1
            continue

        heading = HEADING_RE.match(line)
        if heading:
            flush_paragraph()
            blocks.append(Block('heading', line.rstrip(), index + 1, level=len(heading.group(1)), text=heading.group(2).strip()))
            index += 1
            continue

        if TABLE_RE.match(line):
            flush_paragraph()
            start = index
            rows: list[str] = []
            while index < total and TABLE_RE.match(lines[index]):
                rows.append(lines[index])
                index += 1
            blocks.append(Block('table', normalize_raw(rows), start + 1))
            continue

        if THEMATIC_RE.match(line):
            flush_paragraph()
            blocks.append(Block('thematic', line.rstrip(), index + 1))
            index += 1
            continue

        if QUOTE_RE.match(line):
            flush_paragraph()
            start = index
            quoted: list[str] = []
            while index < total and QUOTE_RE.match(lines[index]):
                quoted.append(lines[index])
                index += 1
            blocks.append(Block('quote', normalize_raw(quoted), start + 1))
            continue

        if LIST_RE.match(line):
            flush_paragraph()
            start = index
            items: list[str] = []
            while index < total:
                candidate = lines[index]
                marker = LIST_RE.match(candidate)
                if marker:
                    items.append(candidate)
                    index += 1
                    continue
                if not candidate.strip():
                    break
                if HEADING_RE.match(candidate) or FENCE_RE.match(candidate) or TABLE_RE.match(candidate) or THEMATIC_RE.match(candidate) or QUOTE_RE.match(candidate):
                    break
                items.append(candidate)
                index += 1
            blocks.append(Block('list', normalize_raw(items), start + 1))
            continue

        if line.lstrip().startswith('<'):
            flush_paragraph()
            start = index
            html: list[str] = []
            while index < total and lines[index].strip() and lines[index].lstrip().startswith('<'):
                html.append(lines[index])
                index += 1
            blocks.append(Block('html', normalize_raw(html), start + 1))
            continue

        if not paragraph:
            paragraph_start = index + 1
        paragraph.append(line)
        index += 1

    flush_paragraph()
    return blocks


def parse_document(path: Path, text: str | None = None) -> Document:
    """Parse one Markdown file into headings, sections and top-level blocks."""
    content = path.read_text(encoding='utf-8') if text is None else text
    content = content.replace('\r\n', '\n').replace('\r', '\n')
    blocks = parse_blocks(content)
    sections: list[Section] = []
    stack: list[tuple[int, str]] = []
    seen: dict[str, int] = {}
    preamble: list[Block] = []
    current: Section | None = None
    errors: list[str] = []

    for block in blocks:
        if block.kind == 'heading':
            while stack and stack[-1][0] >= block.level:
                stack.pop()
            stack.append((block.level, slugify(block.text)))
            base = '/' + '/'.join(part for _, part in stack)
            count = seen.get(base, 0) + 1
            seen[base] = count
            key = base if count == 1 else f'{base}~{count}'
            current = Section(key, block.level, block.text, block.line)
            sections.append(current)
            continue
        if current is None:
            preamble.append(block)
        else:
            current.blocks.append(block)

    if sections and sections[0].level != 1:
        errors.append('文档必须以一级标题开始')
    if preamble:
        errors.append('一级标题之前不允许正文')
    return Document(path, content, blocks, sections, preamble, errors)


def section_text(section: Section) -> str:
    """Hash input: section body without headings and fenced code blocks."""
    parts = [block.raw for block in section.blocks if block.kind not in ('heading', 'code')]
    return normalize_raw([part for part in parts if part.strip()])


def section_hash(section: Section) -> str:
    """Return the 16 hex chars recorded for one section."""
    return hashlib.sha256(section_text(section).encode('utf-8')).hexdigest()[:16]


def compute_hashes(document: Document) -> dict[str, str]:
    """Return ``section key -> 16 hex chars`` for non-empty same-language sections."""
    hashes: dict[str, str] = {}
    for section in document.sections:
        if section_text(section):
            hashes[section.key] = section_hash(section)
    return hashes


def aligned_hashes(
    zh_document: Document, en_document: Document
) -> tuple[dict[str, tuple[str, str]] | None, str | None]:
    """Align both languages by section order; keys come from the primary document."""
    if len(zh_document.sections) != len(en_document.sections):
        return None, f'小节数量不一致（中文 {len(zh_document.sections)}，英文 {len(en_document.sections)}）'
    record: dict[str, tuple[str, str]] = {}
    for zh_section, en_section in zip(zh_document.sections, en_document.sections):
        if not section_text(zh_section) and not section_text(en_section):
            continue
        record[zh_section.key] = (section_hash(en_section), section_hash(zh_section))
    return record, None


def mask_code(text: str) -> str:
    """Blank inline code and HTML comments while keeping character offsets."""
    def blank(match: re.Match[str]) -> str:
        return ' ' * len(match.group(0))

    text = HTML_COMMENT_RE.sub(blank, text)
    return INLINE_CODE_RE.sub(blank, text)


def extract_links(raw: str) -> list[str]:
    """Return link targets in order, skipping images-in-code and generated regions."""
    text = mask_code(raw)
    targets = [match.group(1) for match in LINK_RE.finditer(text)]
    return [target for target in targets if not target.startswith('!')]


def semantic_target(target: str) -> str:
    """Normalize a link target so translated docs compare equal."""
    value = target.strip()
    if value.startswith('<') and value.endswith('>'):
        value = value[1:-1]
    value = value.split(' ')[0]
    path, _, fragment = value.partition('#')
    path, _, query = path.partition('?')
    if path.endswith('.en.md'):
        path = path[: -len('.en.md')] + '.md'
    normalized = path
    if query:
        normalized += '?' + query
    if fragment:
        normalized += '#' + fragment
    return normalized


def _list_shape(raw: str) -> tuple[str, int, int]:
    markers = [LIST_RE.match(line) for line in raw.splitlines()]
    matches = [match for match in markers if match]
    ordered = bool(matches) and matches[0].group(2)[0].isdigit()  # type: ignore[index]
    start = 1
    if ordered and matches:
        start = int(re.match(r'\d+', matches[0].group(2)).group(0))  # type: ignore[union-attr,index]
    return ('ordered' if ordered else 'bullet', start, len(matches))


def _table_shape(raw: str) -> tuple[int, int]:
    rows = [line for line in raw.splitlines() if line.strip()]
    data_rows = [line for line in rows if not SEPARATOR_RE.match(line)]
    columns = 0
    for line in data_rows:
        cells = [cell for cell in line.strip().strip('|').split('|')]
        columns = max(columns, len(cells))
    return (len(data_rows), columns)


def structure_tokens(document: Document) -> list[tuple[object, ...]]:
    """Shape signature: heading levels, list/table shape, semantic links, verbatim code."""
    tokens: list[tuple[object, ...]] = []
    for section in document.sections:
        tokens.append(('section', section.level))
        for block in section.blocks:
            if block.kind == 'heading':
                continue
            if block.kind == 'code':
                tokens.append(('code', block.info, block.body))
                continue
            if block.kind == 'list':
                tokens.append(('list', *_list_shape(block.raw)))
            elif block.kind == 'table':
                tokens.append(('table', *_table_shape(block.raw)))
            for target in extract_links(block.raw):
                tokens.append(('link', semantic_target(target)))
    return tokens


def parse_record(text: str) -> tuple[dict[str, tuple[str, str]], list[str]]:
    """Parse an i18n record into ``key -> (en hash, zh hash)`` plus format errors."""
    record: dict[str, tuple[str, str]] = {}
    errors: list[str] = []
    entries = [line.rstrip() for line in text.replace('\r\n', '\n').splitlines()]
    entries = [line for line in entries if line.strip() and not line.lstrip().startswith('#')]
    index = 0
    while index < len(entries):
        key_line = entries[index]
        if index + 2 >= len(entries):
            errors.append(f'记录在第 {index + 1} 行截断，缺少 en/zh 哈希')
            break
        en_line = entries[index + 1]
        zh_line = entries[index + 2]
        if not (key_line.startswith('/') and key_line.endswith(':') and ' ' not in key_line):
            errors.append(f'非法小节键：{key_line!r}')
            break
        key = key_line[:-1]
        if key in record:
            errors.append(f'重复小节键：{key}')
        en_match = re.fullmatch(r'  en: ([0-9a-f]{16})', en_line)
        zh_match = re.fullmatch(r'  zh: ([0-9a-f]{16})', zh_line)
        if not en_match or not zh_match:
            errors.append(f'小节 {key} 的 en/zh 哈希格式错误')
        else:
            record[key] = (en_match.group(1), zh_match.group(1))
        index += 3
    return record, errors


def render_record(record: dict[str, tuple[str, str]]) -> str:
    """Render the canonical record in primary-document section order."""
    lines = list(RECORD_HEADER)
    for key, (en_hash, zh_hash) in record.items():
        lines.append(f'{key}:')
        lines.append(f'  en: {en_hash}')
        lines.append(f'  zh: {zh_hash}')
    return '\n'.join(lines) + '\n'


def switcher_line(locale: str, source_name: str) -> str:
    """Return the language switch line required after the H1."""
    if locale == 'zh':
        return f'[English]({source_name[:-3]}.en.md) | 中文'
    return f'English | [中文]({source_name})'


def first_content_after_h1(document: Document) -> str | None:
    """Return the first non-blank line after the H1, or ``None``."""
    if not document.sections:
        return None
    lines = document.text.splitlines()
    for line in lines[document.sections[0].line:]:
        if line.strip():
            return line.strip()
    return None


def pair_files(source: Path) -> tuple[Path, Path, Path]:
    """Return ``(zh, en, record)`` paths for a primary Markdown file."""
    base = source.with_suffix('')
    return source, base.with_suffix('.en.md'), base.with_suffix('.i18n.yaml')


def is_generated_region(line: str) -> bool:
    """Generated regions are excluded from the wrap rule only; hashes keep them."""
    return line.strip() in (GENERATED_BEGIN, GENERATED_END)
